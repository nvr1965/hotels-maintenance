-- Гостиничное приложение, PostgreSQL. Сеть → отели → объекты, любые языки.
--
--   psql -U <пользователь> -d <база> -v ON_ERROR_STOP=1 -f 01_schema.sql
--
-- Тексты на языках хранятся в jsonb вида {"ru": "...", "en": "..."}: справочники, заголовки отеля,
-- заявки. Набор языков — таблица languages, новый язык добавляется строкой, без правки схемы.
-- Повторный запуск безопасен (IF NOT EXISTS).

BEGIN;

-- ---------------------------------------------------------------- языки

CREATE TABLE IF NOT EXISTS languages (
    code        text PRIMARY KEY CHECK (code ~ '^[a-z]{2,3}(-[A-Za-z]{2,4})?$'),
    name        text NOT NULL,                       -- по-английски: Russian
    native_name text,                                -- на самом языке: Русский
    is_rtl      boolean NOT NULL DEFAULT false,
    is_active   boolean NOT NULL DEFAULT true,
    sort_order  integer NOT NULL DEFAULT 100
);
COMMENT ON TABLE languages IS 'Языки системы. Английский — основа интерфейса, его не удаляют';

INSERT INTO languages (code, name, native_name, is_rtl, sort_order) VALUES
    ('en', 'English', 'English', false, 10),
    ('ru', 'Russian', 'Русский', false, 20),
    ('he', 'Hebrew', 'עברית', true, 30),
    ('ar', 'Arabic', 'العربية', true, 40)
ON CONFLICT (code) DO NOTHING;

-- Тексты интерфейса. Английские лежат в коде (lang/en.json), здесь — остальные языки.
-- is_auto: переведено автоматически (такие можно перевести заново), false — поправлено человеком.
CREATE TABLE IF NOT EXISTS ui_translations (
    key           text NOT NULL,
    language_code text NOT NULL REFERENCES languages(code) ON UPDATE CASCADE ON DELETE CASCADE,
    text          text NOT NULL,
    is_auto       boolean NOT NULL DEFAULT true,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (key, language_code)
);

-- Кеш перевода на лету (заметки, комментарии, любой свободный текст): один раз перевели — дальше из кеша
CREATE TABLE IF NOT EXISTS translation_cache (
    src_hash   char(64) NOT NULL,                    -- sha256 исходного текста
    from_lang  text NOT NULL,
    to_lang    text NOT NULL,
    text       text NOT NULL,
    provider   text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (src_hash, from_lang, to_lang)
);

-- ---------------------------------------------------------------- сеть и отели

CREATE TABLE IF NOT EXISTS organizations (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    slug       text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,59}$'),
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hotels (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id        integer NOT NULL REFERENCES organizations(id),
    name          text NOT NULL,
    slug          text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,59}$'),
    timezone      text NOT NULL DEFAULT 'UTC',
    default_lang  text NOT NULL DEFAULT 'en',
    languages     text[] NOT NULL DEFAULT '{en}',    -- языки отеля из таблицы languages, по порядку
    brand_title   jsonb NOT NULL DEFAULT '{}',       -- заголовок экрана входа на каждом языке
    brand_subtitle text,
    color_primary char(7) NOT NULL DEFAULT '#1f3a5f',
    color_accent  char(7) NOT NULL DEFAULT '#c9a96e',
    color_text    char(7) NOT NULL DEFAULT '#ffffff',
    color_button  char(7) NOT NULL DEFAULT '#1f3a5f',
    logo_url      text,
    address       text,
    settings      jsonb NOT NULL DEFAULT '{}',       -- push_roles, meter_ocr, icons …
    active        boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hotels_org_idx ON hotels (org_id);

-- ---------------------------------------------------------------- люди

CREATE TABLE IF NOT EXISTS users (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login         text NOT NULL,
    display_name  text NOT NULL,
    password_hash text NOT NULL DEFAULT '',
    lang          text NOT NULL DEFAULT 'en',
    active        boolean NOT NULL DEFAULT true,
    is_superadmin boolean NOT NULL DEFAULT false,    -- владелец системы
    last_hotel_id integer,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_login_uq ON users (lower(login));

CREATE TABLE IF NOT EXISTS org_members (
    org_id     integer NOT NULL REFERENCES organizations(id),
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role       text NOT NULL DEFAULT 'org_viewer' CHECK (role IN ('org_admin', 'org_viewer')),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (org_id, user_id)
);
CREATE INDEX IF NOT EXISTS org_members_user_idx ON org_members (user_id);

-- worker — Исполнитель, manager — Менеджер, head — Руководитель; is_admin — администратор отеля
CREATE TABLE IF NOT EXISTS hotel_members (
    hotel_id   integer NOT NULL REFERENCES hotels(id),
    user_id    integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role       text NOT NULL DEFAULT 'worker' CHECK (role IN ('worker', 'manager', 'head')),
    is_admin   boolean NOT NULL DEFAULT false,
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (hotel_id, user_id)
);
CREATE INDEX IF NOT EXISTS hotel_members_user_idx ON hotel_members (user_id);

-- «Запомнить меня»: хранится только sha256 от validator
CREATE TABLE IF NOT EXISTS auth_tokens (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    selector       char(24) NOT NULL UNIQUE,
    validator_hash char(64) NOT NULL,
    user_id        integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lang           text NOT NULL DEFAULT 'en',
    hotel_id       integer,
    user_agent     text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    last_used_at   timestamptz,
    expires_at     timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_tokens_user_idx ON auth_tokens (user_id);

-- ---------------------------------------------------------------- справочники (у каждого отеля свои)

-- Названия объектов. term_key — постоянный ключ (английское название из Ramada), на него ссылается hotel_assets.asset_key
CREATE TABLE IF NOT EXISTS asset_dictionary (
    id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id integer NOT NULL REFERENCES hotels(id),
    term_key text NOT NULL,
    names    jsonb NOT NULL DEFAULT '{}',
    UNIQUE (hotel_id, term_key)
);

-- Объекты: номера (asset_key из цифр) и прочее (asset_key = term_key справочника)
CREATE TABLE IF NOT EXISTS hotel_assets (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id  integer NOT NULL REFERENCES hotels(id),
    building  text,
    floor     text,
    asset_key text NOT NULL
);
CREATE INDEX IF NOT EXISTS hotel_assets_key_idx ON hotel_assets (hotel_id, asset_key);

CREATE TABLE IF NOT EXISTS room_checklist_dict (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id   integer NOT NULL REFERENCES hotels(id),
    names      jsonb NOT NULL DEFAULT '{}',
    sort_order integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS room_checklist_dict_hotel_idx ON room_checklist_dict (hotel_id);

CREATE TABLE IF NOT EXISTS routine_tasks (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id     integer NOT NULL REFERENCES hotels(id),
    names        jsonb NOT NULL DEFAULT '{}',
    requires_ocr boolean NOT NULL DEFAULT false,
    ocr_type     text,
    sort_order   integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS routine_tasks_hotel_idx ON routine_tasks (hotel_id);

-- ---------------------------------------------------------------- работа

-- Заявки: current (срочная) | planned (плановый обход).
-- description: {"ru": "…", "he": "…"}; description_lang — язык, на котором написал автор (оригинал).
-- Остальные языки дописываются переводом при первом показе.
CREATE TABLE IF NOT EXISTS maintenance_tasks (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id         integer NOT NULL REFERENCES hotels(id),
    task_type        text NOT NULL DEFAULT 'current',
    asset_id         integer,
    user_id          integer,       -- автор срочной
    creator_id       integer,       -- автор плановой
    worker_id        integer,       -- кто закрыл
    description      jsonb NOT NULL DEFAULT '{}',
    description_lang text,
    status           text NOT NULL DEFAULT 'pending',
    notes            text,
    notes_lang       text,
    media            text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz
);
CREATE INDEX IF NOT EXISTS maintenance_tasks_status_idx ON maintenance_tasks (hotel_id, status);
CREATE INDEX IF NOT EXISTS maintenance_tasks_type_idx ON maintenance_tasks (hotel_id, task_type);
CREATE INDEX IF NOT EXISTS maintenance_tasks_asset_idx ON maintenance_tasks (asset_id);

CREATE TABLE IF NOT EXISTS task_workers (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id   integer NOT NULL,
    worker_id integer NOT NULL
);
CREATE INDEX IF NOT EXISTS task_workers_task_idx ON task_workers (task_id);
CREATE INDEX IF NOT EXISTS task_workers_worker_idx ON task_workers (worker_id);

CREATE TABLE IF NOT EXISTS task_room_checks (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id      integer NOT NULL,
    check_id     integer NOT NULL,
    status       text NOT NULL DEFAULT 'pending',
    comment      jsonb NOT NULL DEFAULT '{}',
    comment_lang text
);
CREATE INDEX IF NOT EXISTS task_room_checks_idx ON task_room_checks (task_id, check_id);

CREATE TABLE IF NOT EXISTS routine_schedule (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id    integer NOT NULL,
    task_id     integer NOT NULL,
    worker_id   integer,
    target_date date NOT NULL,
    status      text NOT NULL DEFAULT 'pending',
    notes       text,
    notes_lang  text,
    media       text,
    ocr_value   text,
    ocr_unit    text,
    ocr_raw     text,
    UNIQUE (task_id, target_date)
);
CREATE INDEX IF NOT EXISTS routine_schedule_date_idx ON routine_schedule (hotel_id, target_date);

CREATE TABLE IF NOT EXISTS routine_log (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id    integer NOT NULL,
    schedule_id integer,
    task_id     integer NOT NULL,
    worker_id   integer,
    target_date date NOT NULL,
    status      text NOT NULL DEFAULT 'done' CHECK (status IN ('pending', 'done')),
    notes       text,
    notes_lang  text,
    media       text,
    ocr_value   text,
    ocr_unit    text,
    ocr_raw     text,
    is_repeat   boolean NOT NULL DEFAULT false,
    closed_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS routine_log_task_idx ON routine_log (task_id, target_date);
CREATE INDEX IF NOT EXISTS routine_log_hotel_idx ON routine_log (hotel_id, target_date);
CREATE INDEX IF NOT EXISTS routine_log_worker_idx ON routine_log (worker_id);

CREATE TABLE IF NOT EXISTS meter_report_links (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id     integer NOT NULL REFERENCES hotels(id),
    link_key     char(32) NOT NULL UNIQUE,
    label        text NOT NULL DEFAULT '',
    lang         text NOT NULL DEFAULT 'en',
    created_by   integer,
    created_at   timestamptz NOT NULL DEFAULT now(),
    last_used_at timestamptz,
    revoked      boolean NOT NULL DEFAULT false
);

-- ---------------------------------------------------------------- уведомления и журнал

CREATE TABLE IF NOT EXISTS push_subscriptions (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint      text NOT NULL,
    endpoint_hash char(64) NOT NULL UNIQUE,
    p256dh        text NOT NULL,
    auth          text NOT NULL,
    lang          text NOT NULL DEFAULT 'en',
    silent        boolean NOT NULL DEFAULT false,
    user_agent    text,
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_ok_at    timestamptz
);
CREATE INDEX IF NOT EXISTS push_subscriptions_user_idx ON push_subscriptions (user_id);

CREATE TABLE IF NOT EXISTS push_log (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id   integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    kind       text NOT NULL,
    task_id    integer NOT NULL,
    sent       integer NOT NULL DEFAULT 0,
    ok         integer NOT NULL DEFAULT 0,
    note       text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS push_log_hotel_idx ON push_log (hotel_id);

CREATE TABLE IF NOT EXISTS admin_audit (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    org_id      integer,
    hotel_id    integer,
    user_id     integer,
    user_name   text,
    action      text NOT NULL,
    tbl         text NOT NULL,
    row_key     text,
    before_json jsonb,
    after_json  jsonb
);
CREATE INDEX IF NOT EXISTS admin_audit_at_idx ON admin_audit (at);
CREATE INDEX IF NOT EXISTS admin_audit_hotel_idx ON admin_audit (hotel_id);

-- ---------------------------------------------------------------- службы отеля
-- Служба — раздел отеля со своими сотрудниками, заявками, регламентами и чек-листами
-- (обслуживание здания, уборка номеров, кухня…). Название на языках отеля, как у справочников.
CREATE TABLE IF NOT EXISTS hotel_departments (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id   integer NOT NULL REFERENCES hotels(id),
    names      jsonb NOT NULL DEFAULT '{}',
    icon       text NOT NULL DEFAULT '🛠️',
    color      char(7) NOT NULL DEFAULT '#1f3a5f',
    sort_order integer NOT NULL DEFAULT 0,
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS hotel_departments_hotel_idx ON hotel_departments (hotel_id);

-- Основная служба сотрудника; дополнительные (для тех, кто работает в нескольких) — в member_departments
ALTER TABLE hotel_members ADD COLUMN IF NOT EXISTS department_id integer REFERENCES hotel_departments(id) ON DELETE SET NULL;
CREATE TABLE IF NOT EXISTS member_departments (
    hotel_id      integer NOT NULL REFERENCES hotels(id),
    user_id       integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    department_id integer NOT NULL REFERENCES hotel_departments(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, department_id)
);

ALTER TABLE maintenance_tasks   ADD COLUMN IF NOT EXISTS department_id integer REFERENCES hotel_departments(id) ON DELETE SET NULL;
ALTER TABLE routine_tasks       ADD COLUMN IF NOT EXISTS department_id integer REFERENCES hotel_departments(id) ON DELETE SET NULL;
ALTER TABLE room_checklist_dict ADD COLUMN IF NOT EXISTS department_id integer REFERENCES hotel_departments(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS maintenance_tasks_dep_idx ON maintenance_tasks (department_id);

-- Один раз на отель: служба «Обслуживание здания», в неё — всё, что в отеле уже было
DO $$
DECLARE h record; dep integer;
BEGIN
    FOR h IN SELECT id FROM hotels WHERE NOT (settings ? 'departments_init') LOOP
        INSERT INTO hotel_departments (hotel_id, names, icon, sort_order)
        VALUES (h.id, '{"en": "Building maintenance", "ru": "Обслуживание здания", "he": "תחזוקת מבנה", "ar": "صيانة المبنى"}', '🛠️', 1)
        RETURNING id INTO dep;
        UPDATE hotel_members SET department_id = dep WHERE hotel_id = h.id AND department_id IS NULL;
        UPDATE maintenance_tasks SET department_id = dep WHERE hotel_id = h.id AND department_id IS NULL;
        UPDATE routine_tasks SET department_id = dep WHERE hotel_id = h.id AND department_id IS NULL;
        UPDATE room_checklist_dict SET department_id = dep WHERE hotel_id = h.id AND department_id IS NULL;
        UPDATE hotels SET settings = settings || '{"departments_init": true}' WHERE id = h.id;
    END LOOP;
END $$;

-- ---------------------------------------------------------------- шаблоны структуры отеля
-- Корпуса, этажи, номера и общие объекты (см. backend/core/templates.php). Ведёт владелец системы;
-- по шаблону заводятся объекты нового отеля, дальше отель правится сам по себе.
CREATE TABLE IF NOT EXISTS hotel_templates (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL,
    structure  jsonb NOT NULL DEFAULT '{}',
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

COMMIT;
